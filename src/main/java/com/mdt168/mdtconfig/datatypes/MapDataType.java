package com.mdt168.mdtconfig.datatypes;

import com.mdt168.mdtconfig.ConfigSetting;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.LinkedHashMap;
import java.util.Map;
















































































































































































































































































































































































































































































































































































































































































































































































































































































































public class MapDataType<V> implements ConfigDataType<Map<@NotNull String, @NotNull V>> {
    private final ConfigDataType<V> valueType;

    public MapDataType(@NotNull ConfigDataType<V> valueType) {
        this.valueType = valueType;
    }

    @Override
    public @NotNull Object serialize(@NotNull Map<@NotNull String, @NotNull V> value) {
        return value;
    }

    @Override
    public @Nullable Map<@NotNull String, @NotNull V> deserialize(@NotNull Object object) {
        if (!(object instanceof Map<?,?> rawMap)) {
            return null;
        }
        Map<String, V> map = new LinkedHashMap<>(rawMap.size());

        for (Map.Entry<?, ?> entry : rawMap.entrySet()) {
            V value = valueType.deserialize(entry.getValue());
            if (value == null) {
                return null;
            }
            map.put(String.valueOf(entry.getKey()), value);
        }
        return map;
    }

    @Override
    public @NotNull String getName() {
        return "Map (Text To " + valueType.getName() + ")";
    }

    @Override
    public @NotNull Map<@NotNull String, @NotNull V> deserialize(@NotNull Object object, @NotNull ConfigSetting<Map<@NotNull String, @NotNull V>> caller) {
        if (!(object instanceof Map<?,?> rawMap)) {
            return caller.warnAndUseDefault(object);
        }
        Map<String, V> map = new LinkedHashMap<>(rawMap.size());

        for (Map.Entry<?, ?> entry : rawMap.entrySet()) {
            V value = valueType.deserialize(entry.getValue());
            if (value == null) {
                caller.warn("Found an invalid value: " + entry.getValue() + ". Switching to default map");
                return caller.getDefaultValue();
            }
            Object key = entry.getKey();
            if (key == null) {
                caller.warn("Found an invalid key in the map (Can't have null). Switching to default map");
                return caller.getDefaultValue();
            }
            map.put(String.valueOf(key), value);
        }
        return map;
    }
}
